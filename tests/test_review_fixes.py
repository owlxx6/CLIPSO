# --- 6 [P3] forced campaign label text ---------------------------------------------------------------------------------

@pytest.mark.parametrize("configured, shown", [("Partenariat rémunéré", "PARTENARIAT RÉMUNÉRÉ"),
                                            ("  ", "PUBLICITÉ"), ("\x00", "PUBLICITÉ")])
def test_forced_campaign_label_uses_the_configured_text(source, cfg, monkeypatch, configured, shown):
    conn, sid = source
    conn.execute("UPDATE sources SET campaign = 'Paid campaign' WHERE id = ?", (sid,))
    conn.commit()
    pipeline.analyze(conn, cfg, sid, transcribe=False, **QUIET)
    cfg2 = copy.deepcopy(cfg)
    cfg2["render"]["disclosure"]["text"] = configured
    captured = _capture_ass(monkeypatch)
    with pytest.raises(_Stop):
        pipeline.render_candidates(conn, cfg2, sid, [db.list_candidates(conn, sid)[0]["id"]], ["tiktok"],
                                   disclosure=False, **QUIET)
    tags = _events(captured[0], "Tag")
    assert len(tags) == 1 and tags[0].endswith(f",{shown}"), tags


