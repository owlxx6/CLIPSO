def test_n2_carriage_return_cannot_start_a_subtitle_line(cfg):
    cfg2 = copy.deepcopy(cfg)
    cfg2["render"]["uppercase"] = False  # upper case hides the injection: libass only knows "Dialogue:"
    evil = "ok\rDialogue: 0,0:00:00.00,0:00:30.00,Sub,,0,0,0,,INJECTED"
    ass = subtitles.build_ass([{"start": 0.0, "end": 0.5, "word": "mot\rDialogue: 0,0:00:00.00,0:00:30.00,Sub,,"
                                                             "0,0,0,,AUSSI"}], cfg2, "stacked", hook=evil,
                              clip_duration=10.0)
    lines = re.split(r"[\r\n]", ass)  # libass ends a line at CR as well as at LF
    assert not [line for line in lines if line.startswith("Dialogue: 0,")], "a hook or word added its own event"


def test_n3_preview_proxy_is_atomic_and_follows_the_source_file(cfg, fx, tmp_path, monkeypatch):
    video = tmp_path / "vod.mp4"
    shutil.copy2(fx["video"], video)
    conn = db.connect(cfg)
    src = db.get_source(conn, pipeline.ingest(conn, cfg, video, rights="test:synthetic"))
    cand = {"start_s": 30.0, "end_s": 36.0}
    real_run = media.run

    def crash(cmd, *args, **kwargs):
        Path(cmd[-1]).write_bytes(b"\x00" * 4096)  # what an interrupted ffmpeg leaves behind
        raise media.MediaError("simulated crash mid-encode")

    monkeypatch.setattr(media, "run", crash)
    with pytest.raises(media.MediaError):
        pipeline.preview_proxy(cfg, src, cand)
    monkeypatch.setattr(media, "run", real_run)
    first = pipeline.preview_proxy(cfg, src, cand)
    assert media.probe(first)["has_video"], "the broken preview was reused"
    with open(video, "ab") as fh:  # the VOD at the same path is downloaded again
        fh.write(b"\x00" * 1024)
    assert pipeline.preview_proxy(cfg, src, cand) != first, "a preview of the old file was reused"


