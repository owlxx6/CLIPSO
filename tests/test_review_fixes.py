QUIET = dict(log=lambda *_: None)


class _Stop(Exception):
    """Raised by the fake encoder once the caption file has been captured."""


def _capture_ass(monkeypatch) -> list[str]:
    captured: list[str] = []

    def fake_render(src, start, end, lay, ass_text, out_path, cfg, *args, **kwargs):
        captured.append(ass_text)
        raise _Stop()

    monkeypatch.setattr(render, "render_clip", fake_render)
    return captured


def _events(ass: str, style: str) -> list[str]:
    return [line for line in ass.splitlines() if line.startswith("Dialogue:") and f",{style}," in line]


def _fixture_transcript(fx) -> dict:
    return json.loads(Path(fx["transcript"]).read_text(encoding="utf-8"))


@pytest.fixture()
def whisper_source(cfg, fx, monkeypatch):
    """A source whose transcript was generated by (fake) Whisper during analysis, not imported."""
    monkeypatch.setattr(pipeline.tr, "transcribe", lambda path, tcfg, log=print, *a, **k: _fixture_transcript(fx))
    conn = db.connect(cfg)
    sid = pipeline.ingest(conn, cfg, fx["video"], rights="test:synthetic", chat_file=fx["chat"],
                          clips_file=fx["clips"])
    pipeline.set_layout(cfg, db.get_source(conn, sid), "stacked", fx["facecam"])
    pipeline.analyze(conn, cfg, sid, transcribe=True, **QUIET)
    return conn, sid


# --- 1 [P1] captions after a Whisper setting change ------------------------------------------------------------------

def test_render_keeps_captions_after_a_whisper_setting_change(whisper_source, cfg, monkeypatch):
    conn, sid = whisper_source
    cand = db.list_candidates(conn, sid)[0]
    assert cand["text"]
    cfg2 = copy.deepcopy(cfg)
    cfg2["analysis"]["transcript"]["model"] = "large-v3-turbo"
    captured = _capture_ass(monkeypatch)
    with pytest.raises(_Stop):
        pipeline.render_candidates(conn, cfg2, sid, [cand["id"]], ["tiktok"], **QUIET)
    assert _events(captured[0], "Sub"), "the clip was rendered without captions"


def test_render_refuses_a_clip_whose_captions_are_missing(whisper_source, cfg, monkeypatch):
    conn, sid = whisper_source
    cand = db.list_candidates(conn, sid)[0]
    assert cand["text"]
    (pipeline.workdir(cfg, sid) / "transcript.generated.json").unlink()  # lost, or made from another file
    captured = _capture_ass(monkeypatch)
    with pytest.raises(RuntimeError, match=f"clipper analyze {sid}"):
        pipeline.render_candidates(conn, cfg, sid, [cand["id"]], ["tiktok"], **QUIET)
    assert captured == [], "rendering started without captions"
    assert db.list_exports(conn, source_id=sid) == []


# --- 2 [P2] first-version transcript.json ----------------------------------------------------------------------------

def test_first_version_transcript_needs_explicit_binding_and_then_renders(cfg, fx, monkeypatch):
    conn = db.connect(cfg)
    sid = pipeline.ingest(conn, cfg, fx["video"], rights="test:synthetic", chat_file=fx["chat"],
                          clips_file=fx["clips"])
    pipeline.set_layout(cfg, db.get_source(conn, sid), "stacked", fx["facecam"])
    wd = pipeline.workdir(cfg, sid)
    legacy = _fixture_transcript(fx)
    (wd / "transcript.json").write_text(json.dumps(legacy, ensure_ascii=False), encoding="utf-8")
    logs: list[str] = []
    src = db.get_source(conn, sid)
    assert pipeline.get_transcript(cfg, src, transcribe=False, log=logs.append) is None
    pipeline.bind_transcript(fx["video"], wd / "transcript.json", wd, src["duration"])
    pipeline.analyze(conn, cfg, sid, transcribe=False, log=logs.append)
    cand = db.list_candidates(conn, sid)[0]
    captured = _capture_ass(monkeypatch)
    with pytest.raises(_Stop):
        pipeline.render_candidates(conn, cfg, sid, [cand["id"]], ["tiktok"], log=logs.append)
    assert _events(captured[0], "Sub"), "the first-version transcript was ignored: no captions"
    assert tr.load(wd / "transcript.bound.json")["transcript"] == legacy
    assert (wd / "transcript.json").exists(), "the original file must stay where it was"
    assert sum("no recording identity" in m for m in logs) == 1, logs


def test_force_can_generate_speech_while_preserving_unbound_legacy(cfg, tmp_path, monkeypatch):
    video = tmp_path / "source.mp4"
    video.touch()
    source = {"id": 1, "path": str(video)}
    folder = pipeline.workdir(cfg, 1)
    old = {"segments": []}
    tr.save(folder / "transcript.json", old)
    assert pipeline.get_transcript(cfg, source, transcribe=False) is None
    fresh = {"language": "fr", "segments": []}
    monkeypatch.setattr(tr, "transcribe", lambda *args: fresh)
    assert pipeline.get_transcript(cfg, source, force=True) == fresh
    assert tr.load(folder / "transcript.json") == old
    assert pipeline.get_transcript(cfg, source, transcribe=False) == fresh


# --- 3 [P3] migration and automatic hooks ----------------------------------------------------------------------------

def test_migration_freezes_only_hooks_that_differ_from_the_automatic_one(cfg, fx):
    tdata = _fixture_transcript(fx)
    peak = fixture.BURSTS[0] + 0.5
    profile_dir = config.project_root() / "config" / "streamers"
    profile_dir.mkdir(parents=True)
    (profile_dir / "fixture.yaml").write_text("render:\n  hook:\n    max_words: 1\n", encoding="utf-8")
    auto = tr.peak_phrase(tdata, peak, max_words=1)
    assert auto != tr.peak_phrase(tdata, peak, int(cfg["render"]["hook"]["max_words"]))
    path = config.data_dir(cfg) / "clipper.sqlite"
    with sqlite3.connect(path) as old:
        old.executescript("""
            CREATE TABLE sources(id INTEGER PRIMARY KEY AUTOINCREMENT, path TEXT, rights TEXT, streamer TEXT);
            CREATE TABLE candidates(id INTEGER PRIMARY KEY AUTOINCREMENT, source_id INTEGER, rank INTEGER,
                                    start_s REAL, end_s REAL, peak_s REAL, score REAL, hook TEXT);
            CREATE TABLE labels(id INTEGER PRIMARY KEY AUTOINCREMENT, source_id INTEGER, start_s REAL,
                                end_s REAL, label INTEGER);
            CREATE TABLE exports(id INTEGER PRIMARY KEY AUTOINCREMENT, candidate_id INTEGER, source_id INTEGER,
                                 platform TEXT, path TEXT, start_s REAL, end_s REAL);
            CREATE TABLE posts(id INTEGER PRIMARY KEY AUTOINCREMENT, export_id INTEGER, platform TEXT);
            INSERT INTO sources VALUES (1, 'with transcript', 'permission', 'fixture'),
                                       (2, 'damaged transcript', 'permission', NULL);
        """)
        old.executemany("INSERT INTO candidates VALUES (?,?,?,?,?,?,?,?)", [
            (1, 1, 1, peak - 14, peak + 8, peak, 3.0, auto),              # written by the tool
            (2, 1, 2, peak - 14, peak + 8, peak, 2.0, "mon hook à moi"),  # written by a person
            (3, 1, 3, 60.0, 80.0, 70.0, 1.0, None),
            (4, 2, 1, peak - 14, peak + 8, peak, 3.0, auto),              # origin unknown: stays frozen
        ])
    old.close()
    damaged_dir = config.data_dir(cfg) / "sources" / "2"
    damaged_dir.mkdir(parents=True)
    tr.save(damaged_dir / "transcript.json", {"segments": [{"text": "incomplete timing"}]})
    legacy_dir = config.data_dir(cfg) / "sources" / "1"
    legacy_dir.mkdir(parents=True)
    (legacy_dir / "transcript.json").write_text(json.dumps(tdata, ensure_ascii=False), encoding="utf-8")
    conn = db.connect(cfg)
    edited = {row["id"]: row["hook_edited"] for row in conn.execute("SELECT id, hook_edited FROM candidates")}
    assert edited == {1: 0, 2: 1, 3: 0, 4: 1}
    conn.close()


# --- 4 [P3] replaced files that cannot be deleted ----------------------------------------------------------------------

@pytest.mark.slow
def test_replacement_survives_an_old_clip_that_cannot_be_deleted(source, cfg, monkeypatch):
    conn, sid = source
    pipeline.analyze(conn, cfg, sid, transcribe=False, **QUIET)
    cand = db.list_candidates(conn, sid)[0]
    first = pipeline.render_candidates(conn, cfg, sid, [cand["id"]], ["tiktok"], **QUIET)[0]
    old_clip = Path(first["path"])
    real_unlink = Path.unlink

    def locked_unlink(self, *args, **kwargs):  # what Windows does while a player has the old clip open
        if self == old_clip:
            raise PermissionError(13, "The process cannot access the file because it is being used", str(self))
        return real_unlink(self, *args, **kwargs)

    monkeypatch.setattr(Path, "unlink", locked_unlink)
    logs: list[str] = []
    redo = pipeline.render_candidates(conn, cfg, sid, [cand["id"]], ["tiktok"], hook="nouveau hook", replace=True,
                                      log=logs.append)[0]
    assert redo["blocked_reason"] is None and Path(redo["path"]).exists()
    assert [e["id"] for e in db.list_exports(conn, source_id=sid)] == [redo["export_id"]]
    assert any(str(old_clip) in m for m in logs), logs


